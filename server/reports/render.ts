/** Report renderers: PDF (vector charts), XLSX (with metadata sheet) and CSV. Metadata is preserved in every format. */
import PDFDocument from 'pdfkit';
import ExcelJS from 'exceljs';
import { getMetric, SOURCE_LABELS, type SourceKey, type Unit } from '@shared/metrics';
import { label } from '@shared/catalog';
import { fmt, fmtDelta, fmtPct, fmtRange, type Lang } from '../insights/format';
import type { ReportContent, TableBlock } from './build';

/** Helvetica (WinAnsi) cannot draw some Unicode characters: map them to safe equivalents. */
export function pdfSafe(s: string): string {
  return s
    .replace(/→/g, '->')
    .replace(/←/g, '<-')
    .replace(/−/g, '-')
    .replace(/[  ]/g, ' ')
    .replace(/≈/g, '~')
    .replace(/×/g, 'x')
    .replace(/[^\x09\x0a\x0d\x20-\x7e -ÿ€’‘“”–—…•]/g, '?');
}

const NAVY = '#0b172a';
const ACCENT = '#e11d2e';
const MUTED = '#5b6678';
const LINE = '#d9e0ea';
const BLUE = '#2563eb';

function cell(v: string | number | null | undefined, unit: Unit | 'text' | undefined, lang: Lang): string {
  if (v === null || v === undefined) return '—';
  if (typeof v === 'string' || unit === 'text' || unit === undefined) return String(v);
  return fmt(v, unit, lang);
}

function metaLines(c: ReportContent): Array<[string, string]> {
  const T = (en: string, fr: string) => (c.language === 'fr' ? fr : en);
  const filters = Object.entries(c.filters)
    .filter(([, v]) => v?.length)
    .map(([k, v]) => `${k}: ${v!.join(', ')}`)
    .join(' · ');
  return [
    [T('Report', 'Rapport'), c.title],
    [T('Period', 'Période'), fmtRange(c.period, c.language)],
    [T('Comparison', 'Comparaison'), c.comparePeriod ? `${fmtRange(c.comparePeriod, c.language)} (${c.compare})` : T('none', 'aucune')],
    [T('Filters', 'Filtres'), filters || T('none', 'aucun')],
    [T('Data mode', 'Mode de données'), c.dataModes.map((m) => m.toUpperCase()).join(', ') || '—'],
    [T('Sources', 'Sources'), c.sources.map((s) => SOURCE_LABELS[s as SourceKey] ?? s).join(', ')],
    [T('Generated', 'Généré le'), new Intl.DateTimeFormat(c.language === 'fr' ? 'fr-FR' : 'en-GB', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Europe/Paris' }).format(new Date(c.generatedAt)) + ' (Europe/Paris)'],
    [T('Generated by', 'Généré par'), c.generatedBy],
  ];
}

/* ---------------- PDF ---------------- */

export async function renderPdf(c: ReportContent): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margins: { top: 50, bottom: 60, left: 48, right: 48 }, bufferPages: true, info: { Title: pdfSafe(c.title), Author: 'Veolia Digital Intelligence', Subject: pdfSafe(fmtRange(c.period, c.language)) } });
  const chunks: Buffer[] = [];
  doc.on('data', (b: Buffer) => chunks.push(b));
  const done = new Promise<Buffer>((res) => doc.on('end', () => res(Buffer.concat(chunks))));
  const lang = c.language;
  const T = (en: string, fr: string) => (lang === 'fr' ? fr : en);
  const W = doc.page.width - 96;
  const bottom = () => doc.page.height - 70;
  const ensure = (h: number) => {
    if (doc.y + h > bottom()) doc.addPage();
  };
  const text = (s: string, opts: PDFKit.Mixins.TextOptions = {}) => doc.text(pdfSafe(s), opts);

  // header
  doc.rect(0, 0, doc.page.width, 92).fill(NAVY);
  doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(18).text(pdfSafe(c.title), 48, 28, { width: W - 120 });
  doc.font('Helvetica').fontSize(10).fillColor('#c7d2e3').text(pdfSafe(`${c.organisation} · ${fmtRange(c.period, lang)}`), 48, 56);
  if (c.dataModes.includes('demo')) {
    doc.roundedRect(doc.page.width - 48 - 110, 30, 110, 24, 4).fill(ACCENT);
    doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(10).text(T('DEMO DATA', 'DONNÉES DÉMO'), doc.page.width - 48 - 110, 37, { width: 110, align: 'center' });
  }
  doc.y = 110;
  doc.fillColor(MUTED).font('Helvetica').fontSize(8.5);
  for (const [k, v] of metaLines(c).slice(1, 5)) text(`${k}: ${v}`, { width: W });
  for (const n of c.notes) {
    doc.moveDown(0.3);
    doc.fillColor(ACCENT).font('Helvetica-Bold').fontSize(9);
    text(n, { width: W });
  }
  doc.moveDown(0.8);

  const heading = (s: string) => {
    ensure(40);
    doc.moveDown(0.6);
    doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(13);
    text(s);
    const y = doc.y + 2;
    doc.moveTo(48, y).lineTo(48 + W, y).lineWidth(0.7).strokeColor(LINE).stroke();
    doc.moveDown(0.5);
  };

  const table = (t: TableBlock) => {
    const cols = t.columns;
    const firstW = cols[0].unit === 'text' ? Math.min(W * 0.42, 220) : W / cols.length;
    const restW = (W - firstW) / Math.max(1, cols.length - 1);
    const widths = cols.map((_, i) => (i === 0 ? firstW : restW));
    if (t.title) {
      ensure(30);
      doc.fillColor(MUTED).font('Helvetica-Oblique').fontSize(8.5);
      text(t.title, { width: W });
      doc.moveDown(0.2);
    }
    const drawRow = (vals: string[], bold: boolean) => {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5);
      const heights = vals.map((v, i) => doc.heightOfString(pdfSafe(v), { width: widths[i] - 6 }));
      const h = Math.max(...heights) + 6;
      ensure(h + 2);
      const y = doc.y;
      let x = 48;
      vals.forEach((v, i) => {
        doc.fillColor(bold ? NAVY : '#1f2937').text(pdfSafe(v), x + 3, y + 3, { width: widths[i] - 6, align: i === 0 || cols[i].unit === 'text' ? 'left' : 'right' });
        x += widths[i];
      });
      doc.moveTo(48, y + h).lineTo(48 + W, y + h).lineWidth(0.4).strokeColor(LINE).stroke();
      doc.y = y + h;
      doc.x = 48;
    };
    drawRow(cols.map((c2) => c2.label), true);
    for (const r of t.rows) drawRow(cols.map((c2) => cell(r[c2.key], c2.unit, lang)), false);
    if (!t.rows.length) {
      doc.font('Helvetica-Oblique').fontSize(8.5).fillColor(MUTED);
      text(T('No data for this period.', 'Aucune donnée sur la période.'));
    }
    doc.moveDown(0.6);
  };

  const chart = (title: string, unit: Unit, points: Array<{ label: string; value: number | null; compare: number | null }>) => {
    const h = 150;
    ensure(h + 40);
    doc.fillColor(MUTED).font('Helvetica').fontSize(8.5);
    text(title);
    const top = doc.y + 6;
    const left = 48 + 46;
    const width = W - 50;
    const vals = points.flatMap((p) => [p.value, p.compare]).filter((v): v is number => v !== null);
    if (!vals.length) {
      text(T('No data', 'Aucune donnée'));
      return;
    }
    const max = Math.max(...vals) * 1.08;
    const min = Math.min(0, Math.min(...vals));
    const y = (v: number) => top + h - ((v - min) / (max - min || 1)) * h;
    const x = (i: number) => left + (points.length <= 1 ? 0 : (i / (points.length - 1)) * width);
    doc.lineWidth(0.4).strokeColor(LINE);
    for (let k = 0; k <= 4; k++) {
      const v = min + ((max - min) * k) / 4;
      doc.moveTo(left, y(v)).lineTo(left + width, y(v)).stroke();
      doc.fillColor(MUTED).fontSize(7).text(pdfSafe(fmt(v, unit, lang)), 48, y(v) - 4, { width: 42, align: 'right' });
    }
    const line = (key: 'value' | 'compare', color: string, dash: boolean) => {
      let started = false;
      doc.lineWidth(1.4).strokeColor(color);
      if (dash) doc.dash(3, { space: 2 });
      else doc.undash();
      points.forEach((p, i) => {
        const v = p[key];
        if (v === null) {
          started = false;
          return;
        }
        if (!started) doc.moveTo(x(i), y(v));
        else doc.lineTo(x(i), y(v));
        started = true;
      });
      doc.stroke();
      doc.undash();
    };
    line('compare', '#9aa5b5', true);
    line('value', BLUE, false);
    doc.fillColor(MUTED).fontSize(7);
    const step = Math.max(1, Math.ceil(points.length / 8));
    points.forEach((p, i) => {
      if (i % step === 0) doc.text(pdfSafe(p.label), x(i) - 25, top + h + 4, { width: 50, align: 'center' });
    });
    doc.y = top + h + 18;
    doc.x = 48;
    doc.fillColor(MUTED).fontSize(7.5);
    text(T('Solid: selected period · Dashed: comparison period', 'Trait plein : période · Pointillés : période de comparaison'));
    doc.moveDown(0.6);
  };

  if (c.summary) {
    heading(T('Executive summary', 'Synthèse'));
    const blocks: Array<[string, typeof c.summary.changed]> = [
      [T('What changed', 'Ce qui a changé'), c.summary.changed],
      [T('Drivers (contributions, not causes)', 'Contributions (et non causes)'), c.summary.drivers],
      [T('Needs attention', 'Points d’attention'), c.summary.attention],
      [T('Recommended actions', 'Actions recommandées'), c.summary.actions],
      [T('Data limitations', 'Limites des données'), c.summary.limitations],
    ];
    for (const [title, items] of blocks) {
      if (!items.length) continue;
      ensure(30);
      doc.fillColor(NAVY).font('Helvetica-Bold').fontSize(10);
      text(title);
      doc.font('Helvetica').fontSize(9).fillColor('#1f2937');
      for (const it of items) {
        ensure(20);
        text(`•  ${it.text[lang]}`, { width: W, indent: 0 });
        doc.moveDown(0.15);
      }
      doc.moveDown(0.4);
    }
  }

  for (const s of c.sections) {
    if (s.id === 'summary') continue;
    heading(s.title);
    if (s.kpis?.length) {
      table({
        title: '',
        columns: [
          { key: 'label', label: T('Indicator', 'Indicateur'), unit: 'text' },
          { key: 'value', label: T('Value', 'Valeur'), unit: 'text' },
          { key: 'compare', label: T('Comparison', 'Comparaison'), unit: 'text' },
          { key: 'change', label: T('Change', 'Évolution'), unit: 'text' },
        ],
        rows: s.kpis.map((k) => ({
          label: k.label + (k.notes.length ? ` (${k.notes.join('; ')})` : ''),
          value: fmt(k.value, k.unit, lang),
          compare: fmt(k.compare, k.unit, lang),
          change: k.showPct ? fmtPct(k.deltaPct, lang) : fmtDelta(k.delta, k.unit, lang),
        })),
      });
    }
    for (const ch of s.charts ?? []) chart(ch.title, ch.unit, ch.points);
    for (const t of s.tables ?? []) table(t);
    for (const para of s.text ?? []) {
      doc.fillColor(MUTED).font('Helvetica-Oblique').fontSize(8.5);
      text(para, { width: W });
      doc.moveDown(0.4);
    }
  }

  // metadata & definitions
  doc.addPage();
  heading(T('About this report', 'À propos de ce rapport'));
  doc.font('Helvetica').fontSize(9).fillColor('#1f2937');
  for (const [k, v] of metaLines(c)) {
    ensure(16);
    text(`${k}: ${v}`, { width: W });
  }
  const used = new Set(c.sections.flatMap((s) => s.kpis?.map((k) => k.metric) ?? []));
  if (used.size) {
    heading(T('Definitions', 'Définitions'));
    for (const id of used) {
      const def = getMetric(id);
      if (!def) continue;
      ensure(30);
      doc.font('Helvetica-Bold').fontSize(9).fillColor(NAVY);
      text(label(def.label, lang));
      doc.font('Helvetica').fontSize(8.5).fillColor(MUTED);
      text(label(def.description, lang), { width: W });
      doc.moveDown(0.3);
    }
  }

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const yFoot = doc.page.height - 40;
    doc.font('Helvetica').fontSize(7.5).fillColor(MUTED);
    doc.text(pdfSafe(`${T('Internal use', 'Usage interne')} · Veolia Digital Intelligence${c.dataModes.includes('demo') ? ` · ${T('DEMO DATA', 'DONNÉES DÉMO')}` : ''}`), 48, yFoot, { width: W / 2, lineBreak: false });
    doc.text(`${i + 1} / ${range.count}`, 48 + W / 2, yFoot, { width: W / 2, align: 'right', lineBreak: false });
  }
  doc.end();
  return done;
}

/* ---------------- XLSX ---------------- */

const numFmt = (unit: Unit | 'text' | undefined): string | undefined => {
  switch (unit) {
    case 'percent':
      return '0.0%';
    case 'currency':
      return '#,##0.00 [$€-x-euro2]';
    case 'position':
    case 'decimal':
      return '0.00';
    case 'count':
      return '#,##0';
    default:
      return undefined;
  }
};

export async function renderXlsx(c: ReportContent): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Veolia Digital Intelligence';
  wb.created = new Date(c.generatedAt);
  const lang = c.language;
  const T = (en: string, fr: string) => (lang === 'fr' ? fr : en);
  const meta = wb.addWorksheet(T('About', 'À propos'));
  meta.columns = [{ width: 24 }, { width: 100 }];
  for (const [k, v] of metaLines(c)) meta.addRow([k, v]);
  for (const n of c.notes) meta.addRow([T('Note', 'Remarque'), n]);
  meta.getColumn(1).font = { bold: true };
  if (c.summary) {
    const ws = wb.addWorksheet(T('Summary', 'Synthèse'));
    ws.columns = [{ width: 26 }, { width: 120 }];
    const add = (title: string, items: typeof c.summary.changed) => items.forEach((it) => ws.addRow([title, it.text[lang]]));
    add(T('What changed', 'Ce qui a changé'), c.summary.changed);
    add(T('Drivers', 'Contributions'), c.summary.drivers);
    add(T('Attention', 'Attention'), c.summary.attention);
    add(T('Actions', 'Actions'), c.summary.actions);
    add(T('Limitations', 'Limites'), c.summary.limitations);
  }
  const kpis = c.sections.flatMap((s) => (s.kpis ?? []).map((k) => ({ section: s.title, ...k })));
  if (kpis.length) {
    const ws = wb.addWorksheet('KPI');
    ws.columns = [
      { header: T('Section', 'Section'), key: 'section', width: 24 },
      { header: T('Indicator', 'Indicateur'), key: 'label', width: 40 },
      { header: T('Metric id', 'Identifiant'), key: 'metric', width: 24 },
      { header: T('Value', 'Valeur'), key: 'value', width: 16 },
      { header: T('Comparison', 'Comparaison'), key: 'compare', width: 16 },
      { header: T('Absolute change', 'Écart absolu'), key: 'delta', width: 16 },
      { header: T('% change', 'Écart %'), key: 'deltaPct', width: 12 },
      { header: T('Data mode', 'Mode'), key: 'mode', width: 12 },
      { header: T('Sources', 'Sources'), key: 'sources', width: 30 },
      { header: T('Notes', 'Remarques'), key: 'notes', width: 60 },
    ];
    ws.getRow(1).font = { bold: true };
    for (const k of kpis) {
      const row = ws.addRow({ section: k.section, label: k.label, metric: k.metric, value: k.value, compare: k.compare, delta: k.delta, deltaPct: k.showPct ? k.deltaPct : null, mode: k.mode.toUpperCase(), sources: k.sources.join(', '), notes: k.notes.join('; ') });
      const f = numFmt(k.unit);
      if (f) for (const col of [4, 5, 6]) row.getCell(col).numFmt = f;
      row.getCell(7).numFmt = '0.0%';
    }
  }
  let n = 0;
  for (const s of c.sections) {
    for (const t of s.tables ?? []) {
      n++;
      const name = `${n}. ${s.title}`.replace(/[*?:\\/[\]]/g, ' ').slice(0, 31);
      const ws = wb.addWorksheet(name);
      if (t.title) ws.addRow([t.title]).font = { italic: true };
      const header = ws.addRow(t.columns.map((col) => col.label));
      header.font = { bold: true };
      for (const r of t.rows) {
        const row = ws.addRow(t.columns.map((col) => r[col.key] ?? null));
        t.columns.forEach((col, i) => {
          const f = numFmt(col.unit);
          if (f) row.getCell(i + 1).numFmt = f;
        });
      }
      ws.columns.forEach((col, i) => (col.width = i === 0 ? 48 : 18));
    }
    for (const ch of s.charts ?? []) {
      n++;
      const ws = wb.addWorksheet(`${n}. ${ch.title}`.replace(/[*?:\\/[\]]/g, ' ').slice(0, 31));
      ws.addRow([T('Bucket', 'Période'), T('Value', 'Valeur'), T('Comparison', 'Comparaison')]).font = { bold: true };
      for (const p of ch.points) {
        const row = ws.addRow([p.label, p.value, p.compare]);
        const f = numFmt(ch.unit);
        if (f) [2, 3].forEach((i) => (row.getCell(i).numFmt = f));
      }
      ws.columns.forEach((col) => (col.width = 18));
    }
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}

/* ---------------- CSV ---------------- */

export function csvEscape(v: unknown): string {
  if (v === null || v === undefined) return '';
  let s = typeof v === 'number' ? (Number.isFinite(v) ? String(Math.round(v * 1e6) / 1e6) : '') : String(v);
  // neutralise spreadsheet formula injection
  if (/^[=+\-@\t\r]/.test(s) && typeof v !== 'number') s = `'${s}`;
  return /[",\n\r;]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function renderCsv(c: ReportContent): Buffer {
  const lines: string[] = [];
  const row = (...cells: unknown[]) => lines.push(cells.map(csvEscape).join(','));
  for (const [k, v] of metaLines(c)) row('#', k, v);
  for (const n of c.notes) row('#', 'note', n);
  lines.push('');
  const kpis = c.sections.flatMap((s) => (s.kpis ?? []).map((k) => ({ section: s.title, ...k })));
  if (kpis.length) {
    row('section', 'metric', 'label', 'value', 'comparison', 'absolute_change', 'pct_change', 'data_mode', 'sources', 'notes');
    for (const k of kpis) row(k.section, k.metric, k.label, k.value, k.compare, k.delta, k.showPct ? k.deltaPct : null, k.mode, k.sources.join('|'), k.notes.join('; '));
    lines.push('');
  }
  for (const s of c.sections) {
    for (const t of s.tables ?? []) {
      row('#', 'table', `${s.title}${t.title ? ` — ${t.title}` : ''}`);
      row(...t.columns.map((col) => col.label));
      for (const r of t.rows) row(...t.columns.map((col) => r[col.key]));
      lines.push('');
    }
  }
  return Buffer.from(`﻿${lines.join('\r\n')}`, 'utf8');
}

/* ---------------- generic table export ---------------- */

export interface TableExport {
  title: string;
  columns: Array<{ key: string; label: string; unit?: Unit | 'text' }>;
  rows: Array<Record<string, unknown>>;
  meta: Array<[string, string]>;
}

export async function renderTable(t: TableExport, format: 'csv' | 'xlsx'): Promise<Buffer> {
  if (format === 'csv') {
    const lines: string[] = [];
    for (const [k, v] of t.meta) lines.push(['#', k, v].map(csvEscape).join(','));
    lines.push('');
    lines.push(t.columns.map((col) => csvEscape(col.label)).join(','));
    for (const r of t.rows) lines.push(t.columns.map((col) => csvEscape(r[col.key])).join(','));
    return Buffer.from(`﻿${lines.join('\r\n')}`, 'utf8');
  }
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Veolia Digital Intelligence';
  const ws = wb.addWorksheet(t.title.replace(/[*?:\\/[\]]/g, ' ').slice(0, 31) || 'Data');
  const header = ws.addRow(t.columns.map((col) => col.label));
  header.font = { bold: true };
  for (const r of t.rows) {
    const row = ws.addRow(t.columns.map((col) => (r[col.key] as ExcelJS.CellValue) ?? null));
    t.columns.forEach((col, i) => {
      const f = numFmt(col.unit);
      if (f) row.getCell(i + 1).numFmt = f;
    });
  }
  ws.columns.forEach((col, i) => (col.width = i === 0 ? 40 : 18));
  const meta = wb.addWorksheet('About');
  meta.columns = [{ width: 24 }, { width: 100 }];
  for (const m of t.meta) meta.addRow(m);
  return Buffer.from(await wb.xlsx.writeBuffer());
}
